#!/usr/bin/env bash
# ==============================================================================
# Яндекс Станция Мини 2 + Mac: Интерактивный веб-установщик
# ==============================================================================

set -e

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$DIR"

echo ""
echo "======================================================================"
echo "  Яндекс Станция Мини 2 + Mac — Установщик голосового ассистента"
echo "======================================================================"
echo ""

# Проверка наличия Python 3
if ! command -v python3 &>/dev/null; then
    echo "❌ Ошибка: python3 не найден в системе."
    echo "   Пожалуйста, установите Python 3 (через brew install python или с python.org)."
    exit 1
fi

PYTHON_VER=$(python3 -c "import sys; print(f'{sys.version_info.major}.{sys.version_info.minor}')")
echo "✓ Обнаружен Python $PYTHON_VER"

# Запуск локального мастера установки
echo "🚀 Запуск локального веб-сервера мастера установки..."
python3 "$DIR/installer/wizard_server.py" 8899
